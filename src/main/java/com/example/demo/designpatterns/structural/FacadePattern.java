package com.example.demo.designpatterns.structural;

/**
 * ============================================================
 * 结构型模式 04 —— 外观模式（Facade / 门面模式）
 * ============================================================
 * 【一句话定义】
 *   为复杂的子系统提供一个统一的简化入口，
 *   让客户端不用知道内部一堆细节。
 *
 * 【经典场景】
 *   - 电脑的"开机键"：按下它 = 主板+CPU+内存+硬盘+风扇一起启动，
 *     你不需要自己逐个调用子系统
 *   - Service 层：Controller 只调 Service，Service 内部编排 DAO、
 *     缓存、消息队列等一堆"子系统"
 *   - SDK 封装：给外部一个简洁的 API，藏起内部实现
 *
 * 【解决什么痛点】
 *   没有 Facade 时，客户端要自己知道"先调 A 再调 B，B 失败要回滚 C"，
 *   耦合高、易出错。有了 Facade，复杂度被封装起来。
 *
 * 【通俗理解】
 *   去餐厅点菜（一个入口），不用自己进后厨协调洗菜、炒菜、摆盘。
 *   餐厅前台就是 Facade。
 *
 * 【与中介者的区别】
 *   外观：客户端 ↔ 门面 ↔ 子系统，是"单向简化"，子系统间不通信
 *   中介者：各个同事对象之间互相通信，通过中介者协调"网状→星型"
 *
 * 【注意】
 *   不违反开闭原则的情况下不禁止绕过 Facade 直接调子系统 ——
 *   它是"推荐入口"，不是"唯一入口"。
 */
public class FacadePattern {

    // ==========================================================
    // 子系统 1：CPU（复杂内部逻辑，客户端不该直接操作）
    // ==========================================================
    static class CPU {
        void start() {
            System.out.println("  [CPU] 自检、加载引导程序");
        }
    }

    // ==========================================================
    // 子系统 2：内存
    // ==========================================================
    static class Memory {
        void start() {
            System.out.println("  [内存] 初始化内存条、建立映射");
        }
    }

    // ==========================================================
    // 子系统 3：硬盘
    // ==========================================================
    static class Disk {
        void start() {
            System.out.println("  [硬盘] 读取操作系统镜像");
        }
    }

    // ==========================================================
    // 外观类（门面）：电脑机箱上的"开机键"
    // 把复杂的启动顺序封装成一个简单方法
    // ==========================================================
    static class ComputerFacade {
        // 门面持有所有子系统的引用
        private final CPU cpu = new CPU();
        private final Memory memory = new Memory();
        private final Disk disk = new Disk();

        // 客户端只需要调这一个方法
        public void powerOn() {
            System.out.println("  [开机键] 按下！开始按固定顺序启动子系统：");
            cpu.start();    // 必须先启动 CPU
            memory.start(); // 再初始化内存
            disk.start();   // 最后读硬盘
        }

        public void powerOff() {
            System.out.println("  [开机键] 关机！按相反顺序关闭：");
            disk.start(); // 实际关机逻辑略，这里仅示意封装思想
        }
    }

    // ==========================================================
    // 演示入口
    // ==========================================================
    public static void main(String[] args) {
        System.out.println("===== 外观模式演示 =====");

        // 没有 Facade 的写法（痛苦）：客户端必须知道所有子系统和调用顺序
        // new CPU().start(); new Memory().start(); new Disk().start();

        // 有 Facade 的写法（舒服）：一个方法搞定
        ComputerFacade computer = new ComputerFacade();
        computer.powerOn();
    }
}
